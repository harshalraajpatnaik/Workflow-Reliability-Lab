export class WebhooksComponent implements OnInit {
  api = inject(ApiService);
  workspaceService = inject(WorkspaceService);

  webhooks = signal<Webhook[]>([]);
  showRegisterModal = signal(false);
  showSecretInfo = signal(false);

  newUrl = '';
  newSecret = '';

  readonly availableEvents = [
    {
      code: 'ANOMALY_DETECTED',
      name: 'Anomaly & Latency Spike',
      desc: 'Dropped workflow steps, network socket timeouts (>5000ms), and retry storms'
    },
    {
      code: 'INVARIANT_VIOLATION',
      name: 'Business Invariant Breach',
      desc: 'Critical invariants (no double charge, refund ceiling exceeded, terminal immutability)'
    },
    {
      code: 'INCIDENT_CREATED',
      name: 'Incident Declared',
      desc: 'Automated or engineer-declared operational incidents impacting workflow runs'
    },
    {
      code: 'EXECUTION_FAILED',
      name: 'Workflow Execution Failed',
      desc: 'Asynchronous sagas or compensation chains that failed or terminated with error'
    },
    {
      code: 'PAYMENT_FAILED',
      name: 'Payment Processing Failed',
      desc: 'Payment gateway declines, duplicate processing attempts, or transaction aborts'
    }
  ];

  selectedEvents = signal<string[]>(['ANOMALY_DETECTED', 'INVARIANT_VIOLATION', 'INCIDENT_CREATED']);
  loading = signal(false);

  constructor() {
    effect(() => {
      const ws = this.workspaceService.currentWorkspace();
      if (ws) {
        this.loadWebhooks(ws.id);
      }
    });
  }

  ngOnInit() {
    const ws = this.workspaceService.currentWorkspace();
    if (ws) {
      this.loadWebhooks(ws.id);
    }
  }

  loadWebhooks(wsId: string) {
    this.api.getWebhooks(wsId).subscribe(res => {
      if (res.success && res.data) {
        this.webhooks.set(res.data);
      }
    });
  }

  toggleEvent(code: string) {
    const current = this.selectedEvents();
    if (current.includes(code)) {
      this.selectedEvents.set(current.filter(c => c !== code));
    } else {
      this.selectedEvents.set([...current, code]);
    }
  }

  isEventSelected(code: string): boolean {
    return this.selectedEvents().includes(code);
  }

  selectAllEvents() {
    this.selectedEvents.set(this.availableEvents.map(e => e.code));
  }

  resetDefaultEvents() {
    this.selectedEvents.set(['ANOMALY_DETECTED', 'INVARIANT_VIOLATION', 'INCIDENT_CREATED']);
  }

  clearEvents() {
    this.selectedEvents.set([]);
  }

  onRegisterSubmit() {
    const ws = this.workspaceService.currentWorkspace();
    if (!ws || !this.newUrl) return;

    this.loading.set(true);
    const data: any = {
      url: this.newUrl.trim(),
      description: 'Workspace Notifications & Alerts',
      eventTypes: this.selectedEvents().length > 0 ? this.selectedEvents().join(',') : '*',
      enabled: true
    };

    if (this.newSecret && this.newSecret.trim()) {
      data.secret = this.newSecret.trim();
    }

    this.api.registerWebhook(ws.id, data).subscribe({
      next: () => {
        this.loading.set(false);
        this.showRegisterModal.set(false);
        this.newUrl = '';
        this.newSecret = '';
        this.selectedEvents.set(['ANOMALY_DETECTED', 'INVARIANT_VIOLATION', 'INCIDENT_CREATED']);
        this.showSecretInfo.set(false);
        this.loadWebhooks(ws.id);
      },
      error: () => {
        this.loading.set(false);
      }
    });
  }

  onDeleteWebhook(webhookId: string) {
    const ws = this.workspaceService.currentWorkspace();
    if (!ws) return;

    if (confirm('Are you sure you want to delete this webhook endpoint? Alerts will no longer be dispatched to it.')) {
      this.api.deleteWebhook(ws.id, webhookId).subscribe({
        next: () => {
          this.loadWebhooks(ws.id);
        }
      });
    }
  }
}
